using System.Text;
using Mono.Cecil;

namespace Sharphy.Core.Engines;

/// <summary>
/// Provides synthesis of zero-overhead private member wrappers leveraging .NET 8+ [UnsafeAccessor] attributes.
/// </summary>
public static class WrapperGeneratorEngine
{
    public static string GenerateWrapper(string assemblyPath, string typeName, string outputPath)
    {
        using var assembly = CecilHelpers.ReadAssemblyReadOnly(assemblyPath);
        var type = CecilHelpers.FindType(assembly.MainModule, typeName);

        if (type == null)
        {
            throw new InvalidOperationException($"Type '{typeName}' was not found in assembly.");
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by Sharphy: CLR Intelligence & Runtime Forensic Bridge");
        sb.AppendLine("// Highly optimized zero-overhead private member accessor via [UnsafeAccessor]");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();

        var rootNamespace = GetRootNamespace(type);
        var safeNamespace = SanitizeDottedNamespace(rootNamespace);
        var wrapperNamespace = string.IsNullOrWhiteSpace(safeNamespace)
            ? "GeneratedWrappers"
            : $"{safeNamespace}.GeneratedWrappers";
        var safeTypeName = CecilHelpers.SanitizeCSharpIdentifier(type.Name);
        var fullTypeExpr = SanitizeDottedTypeExpression(type.FullName);

        sb.AppendLine($"namespace {wrapperNamespace};");
        sb.AppendLine();
        sb.AppendLine($"public static class {safeTypeName}Accessor");
        sb.AppendLine("{");

        var usedNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (var method in type.Methods.Where(m => !m.IsPublic && !m.IsConstructor && !m.IsGetter && !m.IsSetter))
        {
            var isStatic = method.IsStatic;
            var kind = isStatic ? "UnsafeAccessorKind.StaticMethod" : "UnsafeAccessorKind.Method";
            var targetParam = isStatic ? "" : $"{fullTypeExpr} target";
            var otherParams = string.Join(", ", method.Parameters.Select((p, idx) =>
            {
                var pName = string.IsNullOrWhiteSpace(p.Name) ? $"arg{idx}" : CecilHelpers.SanitizeCSharpIdentifier(p.Name);
                return $"{FormatTypeName(p.ParameterType)} {pName}";
            }));
            var allParams = string.IsNullOrEmpty(targetParam)
                ? otherParams
                : (string.IsNullOrEmpty(otherParams) ? targetParam : $"{targetParam}, {otherParams}");

            var candidateName = $"Call_{CecilHelpers.SanitizeCSharpIdentifier(method.Name)}";
            var uniqueMethodName = MakeUniqueIdentifier(candidateName, usedNames);

            sb.AppendLine($"    [UnsafeAccessor({kind}, Name = \"{EscapeCSharpStringLiteral(method.Name)}\")]");
            sb.AppendLine($"    public static extern {FormatTypeName(method.ReturnType)} {uniqueMethodName}({allParams});");
            sb.AppendLine();
        }

        foreach (var field in type.Fields.Where(f => !f.IsPublic))
        {
            var isStatic = field.IsStatic;
            var kind = isStatic ? "UnsafeAccessorKind.StaticField" : "UnsafeAccessorKind.Field";
            var targetParam = isStatic ? "" : $"{fullTypeExpr} target";
            var candidateName = $"Get_{CecilHelpers.SanitizeCSharpIdentifier(field.Name)}";
            var uniqueFieldName = MakeUniqueIdentifier(candidateName, usedNames);

            sb.AppendLine($"    [UnsafeAccessor({kind}, Name = \"{EscapeCSharpStringLiteral(field.Name)}\")]");
            sb.AppendLine($"    public static extern ref {FormatTypeName(field.FieldType)} {uniqueFieldName}({targetParam});");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        var code = sb.ToString();

        var outDir = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrEmpty(outDir) && !Directory.Exists(outDir))
        {
            Directory.CreateDirectory(outDir);
        }

        File.WriteAllText(outputPath, code);
        return code;
    }

    private static string FormatTypeName(TypeReference typeRef, int depth = 0)
    {
        if (depth > 32) return "object";
        if (typeRef.FullName == "System.Void") return "void";
        if (typeRef.IsByReference && typeRef is ByReferenceType byRef)
        {
            return $"ref {FormatTypeName(byRef.ElementType, depth + 1)}";
        }
        if (typeRef is ArrayType arr)
        {
            var commas = arr.Rank > 1 ? new string(',', arr.Rank - 1) : string.Empty;
            return $"{FormatTypeName(arr.ElementType, depth + 1)}[{commas}]";
        }
        if (typeRef is GenericInstanceType git)
        {
            var baseName = git.ElementType.Name;
            var tickIdx = baseName.IndexOf('`');
            if (tickIdx > 0) baseName = baseName[..tickIdx];
            return $"{CecilHelpers.SanitizeCSharpIdentifier(baseName)}<{string.Join(", ", git.GenericArguments.Select(a => FormatTypeName(a, depth + 1)))}>";
        }
        return CecilHelpers.SanitizeCSharpIdentifier(typeRef.Name);
    }

    private static string SanitizeDottedNamespace(string rawNamespace)
    {
        if (string.IsNullOrWhiteSpace(rawNamespace)) return string.Empty;
        return string.Join(".", rawNamespace
            .Split('.', StringSplitOptions.RemoveEmptyEntries)
            .Select(CecilHelpers.SanitizeCSharpIdentifier));
    }

    private static string SanitizeDottedTypeExpression(string rawFullName)
    {
        var normalized = rawFullName.Replace('/', '.');
        var tickIdx = normalized.IndexOf('`');
        if (tickIdx > 0) normalized = normalized[..tickIdx];
        return string.Join(".", normalized
            .Split('.', StringSplitOptions.RemoveEmptyEntries)
            .Select(CecilHelpers.SanitizeCSharpIdentifier));
    }

    private static string EscapeCSharpStringLiteral(string raw)
    {
        if (string.IsNullOrEmpty(raw)) return string.Empty;

        var sb = new StringBuilder(raw.Length);
        foreach (char c in raw)
        {
            switch (c)
            {
                case '\\': sb.Append("\\\\"); break;
                case '\"': sb.Append("\\\""); break;
                case '\0': sb.Append("\\0"); break;
                case '\r': sb.Append("\\r"); break;
                case '\n': sb.Append("\\n"); break;
                case '\t': sb.Append("\\t"); break;
                case '\b': sb.Append("\\b"); break;
                case '\f': sb.Append("\\f"); break;
                default:
                    if (char.IsControl(c))
                        sb.Append($"\\u{(int)c:x4}");
                    else
                        sb.Append(c);
                    break;
            }
        }
        return sb.ToString();
    }

    private static string GetRootNamespace(TypeDefinition type)
    {
        var current = type;
        while (current.DeclaringType != null)
        {
            current = current.DeclaringType;
        }
        return current.Namespace;
    }

    private static string MakeUniqueIdentifier(string baseName, HashSet<string> used)
    {
        if (used.Add(baseName)) return baseName;
        int suffix = 2;
        while (!used.Add($"{baseName}_{suffix}"))
        {
            suffix++;
        }
        return $"{baseName}_{suffix}";
    }
}
